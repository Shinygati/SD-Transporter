"""Build the virtual GBA Slot-2 ARM9 blob and emit common/include/slot2_emu_payload.h.

Run after changing retail/slot2emu/*. The bootstrap build itself only needs
the generated header. The blob must be position independent; this script
links it at two addresses and refuses to emit a header if they differ.
"""
from pathlib import Path
import os, shutil, subprocess, sys

ROOT = Path(__file__).resolve().parent
RETAIL = ROOT / 'retail'
SRC = RETAIL / 'slot2emu'
OUT = SRC / 'build'
INC = RETAIL / 'common/include'
OUT.mkdir(exist_ok=True)

def sdkpath(value):
 if os.name=='nt':
  if value.startswith('/opt/devkitpro'):value='C:/devkitPro'+value[len('/opt/devkitpro'):]
  elif len(value)>3 and value[0]=='/' and value[2]=='/':value=value[1]+':'+value[2:]
 return Path(value)

def tool(name):
    for base in (str(sdkpath(os.environ.get('LEGACY_DEVKITARM',os.environ.get('DEVKITARM', '/opt/devkitpro/devkitARM')))/'bin'), '/usr/bin'):
        path = Path(base) / ('arm-none-eabi-' + name + ('.exe' if os.name == 'nt' else ''))
        if path.exists():
            return str(path)
    path = shutil.which('arm-none-eabi-' + name)
    if path:
        return path
    sys.exit('arm-none-eabi-%s not found (set DEVKITARM)' % name)

CFLAGS = ['-mcpu=arm946e-s', '-marm', '-Os', '-ffreestanding', '-fno-builtin', '-fno-jump-tables',
          '-fno-pic', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-fno-common',
          '-Wall', '-Wextra', '-Werror', '-I' + str(INC)]
objs = []
for src, extra in (('slot2emu_entry.s', ['-x', 'assembler-with-cpp']), ('slot2emu.c', [])):
    obj = OUT / (Path(src).stem + '.o')
    subprocess.run([tool('gcc')] + CFLAGS + extra + ['-c', str(SRC / src), '-o', str(obj)], check=True)
    objs.append(str(obj))

def link(base):
    elf = OUT / ('slot2emu_%08x.elf' % base)
    binary = OUT / ('slot2emu_%08x.bin' % base)
    subprocess.run([tool('gcc'), '-nostdlib', '-nostartfiles', '-T', str(SRC / 'slot2emu.ld'),
                    '-Wl,--section-start=.text=0x%x' % base, '-o', str(elf)] + objs, check=True)
    subprocess.run([tool('objcopy'), '-O', 'binary', str(elf), str(binary)], check=True)
    return binary.read_bytes(), elf

blob, elf = link(0)
moved, _ = link(0x0CFA9000)
if blob != moved:
    sys.exit('slot2emu blob is not position independent')
if len(blob) > 0x7000:
    sys.exit('slot2emu blob too large: %d bytes' % len(blob))
sections = subprocess.check_output([tool('objdump'), '-h', str(elf)], text=True)
for bad in ('.data', '.bss'):
    if (' %s ' % bad) in sections:
        sys.exit('slot2emu blob has a %s section' % bad)

lines = ['/* Generated by work/build_slot2_emu.py from retail/slot2emu. GPL-3.0-or-later. */',
         '#ifndef SLOT2_EMU_PAYLOAD_H', '#define SLOT2_EMU_PAYLOAD_H',
         'static const unsigned char slot2EmuBlob[%d] __attribute__((aligned(4))) = {' % len(blob)]
for i in range(0, len(blob), 16):
    lines.append('\t' + ','.join('0x%02x' % b for b in blob[i:i + 16]) + ',')
lines += ['};', '#endif', '']
(INC / 'slot2_emu_payload.h').write_text('\n'.join(lines))
print('slot2emu blob: %d bytes' % len(blob))
