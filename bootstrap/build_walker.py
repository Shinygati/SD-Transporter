"""Build the virtual Pokewalker ARM9 blob and IR stub; emit common/include/walker_payload.h.

Run after changing retail/pokewalker/*. Set LEGACY_DEVKITARM to the compiler path. The bootstrap build only needs the
generated header. The blob must be position independent: it is linked at two
addresses and the header is refused if they differ.
"""
from pathlib import Path
import os, shutil, subprocess, sys

ROOT = Path(__file__).resolve().parent
RETAIL = ROOT / 'retail'
SRC = RETAIL / 'pokewalker'
OUT = SRC / 'build'
INC = RETAIL / 'common/include'
OUT.mkdir(exist_ok=True)

def tool(name):
    for base in (os.environ.get('LEGACY_DEVKITARM', '') + '/bin', os.environ.get('DEVKITARM', '/opt/devkitpro/devkitARM') + '/bin', '/usr/bin'):
        path = Path(base) / ('arm-none-eabi-' + name + ('.exe' if os.name == 'nt' else ''))
        if path.exists():
            return str(path)
    path = shutil.which('arm-none-eabi-' + name)
    if path:
        return path
    sys.exit('arm-none-eabi-%s not found (set DEVKITARM)' % name)

CFLAGS = ['-mcpu=arm946e-s', '-marm', '-Os', '-ffreestanding', '-fno-builtin', '-fno-jump-tables',
          '-fno-pic', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-fno-common',
          '-Wall', '-Wextra', '-Werror', '-I' + str(INC)]

def symbols(elf):
    out = subprocess.check_output([tool('nm'), str(elf)], text=True)
    return {p[2]: int(p[0], 16) for p in (l.split() for l in out.splitlines()) if len(p) == 3}

# Walker blob
obj = OUT / 'walker.o'
subprocess.run([tool('gcc')] + CFLAGS + ['-c', str(SRC / 'walker.c'), '-o', str(obj)], check=True)
def link(base):
    elf = OUT / ('walker_%08x.elf' % base)
    binary = OUT / ('walker_%08x.bin' % base)
    subprocess.run([tool('gcc'), '-nostdlib', '-nostartfiles', '-T', str(SRC / 'walker.ld'),
                    '-Wl,--section-start=.text=0x%x' % base, '-o', str(elf), str(obj)], check=True)
    subprocess.run([tool('objcopy'), '-O', 'binary', str(elf), str(binary)], check=True)
    return binary.read_bytes(), elf
blob, elf = link(0)
moved, _ = link(0x0CFB9000)
if blob != moved:
    sys.exit('walker blob is not position independent')
if symbols(elf).get('walkerEntry') != 0:
    sys.exit('walkerEntry must be at offset 0')
if len(blob) > 0x3000:
    sys.exit('walker blob too large: %d bytes' % len(blob))
sections = subprocess.check_output([tool('objdump'), '-h', str(elf)], text=True)
for bad in ('.data', '.bss'):
    if (' %s ' % bad) in sections:
        sys.exit('walker blob has a %s section' % bad)

# IR stub
sobj = OUT / 'walker_stub.o'
selF = OUT / 'walker_stub.elf'
sbin = OUT / 'walker_stub.bin'
subprocess.run([tool('gcc'), '-mcpu=arm946e-s', '-c', str(SRC / 'walker_stub.s'), '-o', str(sobj)], check=True)
subprocess.run([tool('ld'), '-Ttext=0', '-o', str(selF), str(sobj)], check=True)
subprocess.run([tool('objcopy'), '-O', 'binary', str(selF), str(sbin)], check=True)
stub = sbin.read_bytes()
sym = symbols(selF)
if sym['walkerStubEnd'] != len(stub):
    sys.exit('unexpected stub layout')

def table(name, data):
    lines = ['static const unsigned char %s[%d] __attribute__((aligned(4))) = {' % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append('\t' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    return lines + ['};']

lines = ['/* Generated by work/build_walker.py from retail/pokewalker. GPL-3.0-or-later. */',
         '#ifndef WALKER_PAYLOAD_H', '#define WALKER_PAYLOAD_H']
lines += table('walkerBlob', blob) + table('walkerStub', stub)
for name in ('walkerStubWrite', 'walkerStubInit', 'walkerStubControl', 'walkerStubEntry'):
    lines.append('#define %s_OFF 0x%x' % (name.upper().replace('WALKERSTUB', 'WALKER_STUB_'), sym[name]))
lines += ['#endif', '']
(INC / 'walker_payload.h').write_text('\n'.join(lines), encoding='utf-8')
print('walker blob: %d bytes, IR stub: %d bytes' % (len(blob), len(stub)))

# DS Lite / B4DS storage dispatcher. It calls cardengine DLDI services via the
# context table; no absolute game addresses or writable globals are permitted.
dsobj = OUT / 'walker_ds.o'
subprocess.run([tool('gcc')] + CFLAGS + ['-c', str(SRC / 'walker_ds.c'), '-o', str(dsobj)], check=True)
def link_ds(base):
    elf = OUT / ('walker_ds_%08x.elf' % base)
    raw = elf.with_suffix('.bin')
    subprocess.run([tool('gcc'), '-nostdlib', '-nostartfiles', '-T', str(SRC / 'walker.ld'),
                    '-Wl,--section-start=.text=0x%x' % base, '-o', str(elf), str(dsobj)], check=True)
    subprocess.run([tool('objcopy'), '-O', 'binary', str(elf), str(raw)], check=True)
    return raw.read_bytes(), elf
dsblob, dself = link_ds(0)
moved, _ = link_ds(0x023CA800)
if dsblob != moved or symbols(dself).get('walkerDsDispatch') != 0:
    sys.exit('DS walker dispatcher is not position independent at entry 0')
if len(dsblob) > 0x1800 or len(blob) > 0x1800:
    sys.exit('DS walker payloads overlap their reserved areas')
sections = subprocess.check_output([tool('objdump'), '-h', str(dself)], text=True)
for bad in ('.data', '.bss'):
    if (' %s ' % bad) in sections:
        sys.exit('DS walker blob has a %s section' % bad)
meta = ['/* Generated by bootstrap/build_walker.py. GPL-3.0-or-later. */',
        '#ifndef WALKER_DS_PAYLOAD_H', '#define WALKER_DS_PAYLOAD_H',
        '#define WALKER_PROTOCOL_SIZE %du' % len(blob),
        '#define WALKER_IR_STUB_SIZE %du' % len(stub),
        '#define WALKER_DS_RUNTIME_SIZE %du' % len(dsblob),
        '#define WALKER_DS_PAYLOAD_SIZE %du' % (len(blob)+len(stub)+len(dsblob))]
for name in ('walkerStubWrite', 'walkerStubInit', 'walkerStubControl', 'walkerStubEntry'):
    meta.append('#define %s_OFF 0x%x' % (name.upper().replace('WALKERSTUB', 'WALKER_STUB_'), sym[name]))
meta += ['#endif', '']
(INC / 'walker_ds_payload.h').write_text('\n'.join(meta), encoding='utf-8')
(RETAIL / 'nitrofiles/walker_ds.bin').write_bytes(blob + stub + dsblob)
print('DS dispatcher: %d bytes; NitroFS bundle: %d bytes' % (len(dsblob), len(blob)+len(stub)+len(dsblob)))
